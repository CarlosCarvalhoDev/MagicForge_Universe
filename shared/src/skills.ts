/**
 * Retorna todas as 12 habilidades pertencentes à classe especificada
 */
export function getSkillsForClass(classType: CharacterClass): SkillDefinition[] {
  const map = new Map<string, SkillDefinition>();
  for (const s of Object.values(SKILLS_DATABASE)) {
    if (s.classType === classType && (s.skillId.includes('truque') || s.skillId.includes('nv1') || s.skillId.includes('nv2') || s.skillId.includes('nv3'))) {
      map.set(s.skillId, s);
    }
  }
  return Array.from(map.values()).sort((a, b) => a.slot - b.slot || a.choiceIndex - b.choiceIndex);
}

/**
 * Retorna as 3 opções de habilidades para o slot especificado (1 a 4)
 */
export function getSkillChoicesForSlot(classType: CharacterClass, slot: number): SkillDefinition[] {
  return getSkillsForClass(classType).filter((s) => s.slot === slot);
}

/**
 * Retorna o loadout padrão de skills para a classe (Escolha 1 de cada slot)
 */
export function getDefaultSkillsForClass(classType: CharacterClass): Record<number, string> {
  const prefix = classType.toLowerCase();
  return {
    1: `${prefix}_truque_1`,
    2: `${prefix}_nv1_1`,
    3: `${prefix}_nv2_1`,
    4: `${prefix}_nv3_1`,
  };
}

/**
 * Calcula o dano ou cura de uma habilidade com base nos atributos do personagem (D&D 5E)
 */
export function calculateSkillPower(
  skill: SkillDefinition,
  stats: CharacterAttributes,
  level: number,
  maxHp?: number
): number {
  if (skill.classType === CharacterClass.GUERREIRO) {
    switch (skill.skillId) {
      case 'guerreiro_truque_1':
      case 'guerreiro_1':
        return Math.round(stats.forca * 1.35 + level * 4);
      case 'guerreiro_truque_2':
        return Math.round(stats.forca * 1.10 + level * 4);
      case 'guerreiro_truque_3':
        return Math.round(stats.forca * 1.25 + level * 4);
      case 'guerreiro_nv1_1':
      case 'guerreiro_2':
        // Second Wind D&D 5e: 1.6x STR + 2x Nível
        return Math.round(stats.forca * 1.60 + level * 2);
      case 'guerreiro_nv1_2':
        return Math.round(stats.forca * 1.60 + level * 4);
      case 'guerreiro_nv1_3':
        return Math.round(stats.forca * 1.40 + stats.constituicao * 0.50 + level * 4);
      case 'guerreiro_nv2_1':
      case 'guerreiro_3':
        return Math.round(stats.forca * 2.30 + level * 4);
      case 'guerreiro_nv2_2': {
        // Baluarte Inquebrável: Absorve 30% do HP Máximo
        const resolvedMaxHp = maxHp ?? (stats.constituicao * 35 + 450 + Math.max(0, level - 1) * 60);
        return Math.round(resolvedMaxHp * 0.30);
      }
      case 'guerreiro_nv2_3':
        return Math.round(stats.forca * 2.60 + level * 4);
      case 'guerreiro_nv3_1':
      case 'guerreiro_4':
        return Math.round(stats.forca * 3.60 + stats.constituicao * 1.50 + level * 4);
      case 'guerreiro_nv3_2':
        return Math.round(stats.forca * 4.40 + level * 4);
      case 'guerreiro_nv3_3': {
        // Última Resistência Imortal: Cura 40% do HP Máximo
        const resolvedMaxHp = maxHp ?? (stats.constituicao * 35 + 450 + Math.max(0, level - 1) * 60);
        return Math.round(resolvedMaxHp * 0.40);
      }
    }
  }

  let modifier = 0;
  switch (skill.classType) {
    case CharacterClass.GUERREIRO:
    case CharacterClass.BARBARO:
      modifier = stats.forca;
      break;
    case CharacterClass.CLERIGO:
      modifier = stats.sabedoria;
      break;
    case CharacterClass.MAGO:
      modifier = stats.inteligencia;
      break;
    case CharacterClass.ARQUEIRO:
    case CharacterClass.MONGE:
      modifier = stats.destreza;
      break;
    case CharacterClass.BRUXO:
    case CharacterClass.DEMONOLOGO:
      modifier = stats.carisma;
      break;
  }

  if (skill.isHeal) {
    return Math.round(150 + modifier * 6 + level * 20);
  }

  // Escalonamento por Tier (Slot 1: 1.4x, Slot 2: 1.8x, Slot 3: 2.4x, Slot 4: 4.2x)
  const multipliers = [0, 1.4, 1.8, 2.4, 4.2];
  const mult = multipliers[skill.slot] || 1.5;

  const baseRoll = 6; // Rolagem média determinística d8 D&D
  return Math.round(baseRoll + modifier * mult + level * 4);
}
