  const s2 = SKILLS_DATABASE[`${prefix}_nv1_1`];
  const s3 = SKILLS_DATABASE[`${prefix}_nv2_1`];
  const s4 = SKILLS_DATABASE[`${prefix}_nv3_1`];

  if (s1) SKILLS_DATABASE[`${prefix}_1`] = s1;
  if (s2) SKILLS_DATABASE[`${prefix}_2`] = s2;
